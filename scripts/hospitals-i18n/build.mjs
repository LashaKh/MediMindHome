// Rebuild after editing Russian copy or language-specific CSS. No external translation service.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';
import postcss from 'postcss';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const dictionary = JSON.parse(read('scripts/hospitals-i18n/ru.json'));
for (const [source, translation] of Object.entries(dictionary)) {
  if (!source.trim() || !translation.trim()) throw new Error('Empty translation');
  const tags = value => [...value.matchAll(/<\/?([\w-]+)\b/g)].map(match => match[0]).join('|');
  if (tags(source) !== tags(translation)) throw new Error('Markup changed: ' + source.slice(0, 70));
}
const generatedJs = '// Generated by scripts/hospitals-i18n/build.mjs. Edit ru.json and runtime.js instead.\n' +
  'window.mmHospitalRussian = ' + JSON.stringify(dictionary) + ';\n' + read('scripts/hospitals-i18n/runtime.js');
fs.writeFileSync(path.join(root, 'public/deck-assets/hospitals-russian.js'), generatedJs);
const html = read('public/hospitals.html');
const inlineStyles = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(match => match[1]);
const cssFiles = [...html.matchAll(/<link[^>]+href="(\/deck-assets\/[^"?]+\.css)/g)].filter(match => !match[1].endsWith('/hospitals-russian.css')).map(match => read('public' + match[1]));
// Mirror the existing English display rules for Russian, including rules inside media queries.
const generatedRules = [];
for (const source of [...inlineStyles, ...cssFiles]) {
  const ast = postcss.parse(source);
  ast.walkRules(rule => {
    const selectors = rule.selectors.filter(selector => /\.lang-(?:en|active-en)\b/.test(selector) && !/\.lang-(?:ka|active-ka)\b/.test(selector));
    if (!selectors.length) return;
    let clone = rule.clone({ selector: selectors.map(selector => selector.replace(/\.lang-en\b/g, '.lang-ru').replace(/\.lang-active-en\b/g, '.lang-active-ru').replace(/\.btn-en\b/g, '.btn-ru')).join(',\n') });
    for (let parent = rule.parent; parent?.type === 'atrule'; parent = parent.parent) {
      const wrapper = parent.clone({ nodes: [] }); wrapper.append(clone); clone = wrapper;
    }
    generatedRules.push(clone.toString());
  });
}
const css = `/* Generated Russian counterparts of existing language rules. */\n.lang-ru { display: none !important; }\nbody.lang-active-ru .lang-ru { display: inherit !important; }\n${generatedRules.join('\n')}\n${read('scripts/hospitals-i18n/russian-layout.css')}\nhtml:not([lang="ru"]) body .lang-ru, body.lang-active-ru .lang-en, body.lang-active-ru .lang-ka { display: none !important; }\nbody.lang-active-ru .btn-ru { background: rgba(255,255,255,.95) !important; color: #1a365d !important; }\nbody.lang-active-ru { overflow-wrap: break-word; }\n`;
fs.writeFileSync(path.join(root, 'public/deck-assets/hospitals-russian.css'), css);
let updated = html;
for (const file of ['hospitals-russian.js', 'hospitals-russian.css']) {
  const hash = crypto.createHash('sha256').update(read('public/deck-assets/' + file)).digest('hex').slice(0, 10);
  updated = updated.replace(new RegExp(file.replace('.', '\\.') + '\\?v=[a-f0-9]+', 'g'), file + '?v=' + hash);
}
fs.writeFileSync(path.join(root, 'public/hospitals.html'), updated);
console.log(`Built Russian catalogue: ${Object.keys(dictionary).length} entries; ${generatedRules.length} display rules.`);
