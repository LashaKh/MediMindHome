"""Build the hospital proposal translations from reviewed locale JSON files.

Run: python3 -I scripts/partner-i18n/build.py
English HTML fallbacks and public/partner-i18n.js are generated together.
Only <em> and <br> are allowed in the curated copy. All three languages must
have identical keys and matching emphasis/line-break tags before any write.
"""
import json
import re
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCALES = Path(__file__).resolve().parent / 'locales'

class CopyValidator(HTMLParser):
    def handle_starttag(self, tag, attrs):
        if tag not in {'br', 'em'} or attrs:
            raise ValueError(f'Unsupported copy markup: {tag} {attrs}')
    def handle_endtag(self, tag):
        if tag != 'em':
            raise ValueError(f'Unsupported closing tag: {tag}')

translations = {lang: json.loads((LOCALES / f'{lang}.json').read_text()) for lang in ('en', 'ka', 'ru')}
english = translations['en']
for lang, words in translations.items():
    missing, extra = set(english) - set(words), set(words) - set(english)
    if missing or extra:
        raise ValueError(f'{lang}: missing {sorted(missing)}, extra {sorted(extra)}')
    for key, value in words.items():
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f'{lang}.{key}: empty or non-string copy')
        CopyValidator().feed(value)
        if Counter(re.findall(r'</?(?:em|br)>', value)) != Counter(re.findall(r'</?(?:em|br)>', english[key])):
            raise ValueError(f'{lang}.{key}: emphasis or line breaks differ')

path = ROOT / 'public/partner.html'
html = path.read_text()
used = set(re.findall(r'data-t="([^"]+)"', html))
if used - set(english):
    raise ValueError(f'Untranslated HTML keys: {sorted(used - set(english))}')
def fallback(match):
    opening, tag, key = match.group(1), match.group(2), match.group(3)
    return opening + english[key] + '</' + tag + '>'
html = re.sub(r'(<([a-z0-9]+)\b[^>]*\bdata-t="([^"]+)"[^>]*>).*?</\2>', fallback, html, flags=re.S)
script = '/* Generated by scripts/partner-i18n/build.py. Edit locales/*.json. */\nwindow.PARTNER_I18N = ' + json.dumps(translations, ensure_ascii=False, indent=2) + ';\n'
path.write_text(html)
(ROOT / 'public/partner-i18n.js').write_text(script)
print(f'Validated and built {len(english)} keys in all three languages; {len(used)} keys used in HTML.')
