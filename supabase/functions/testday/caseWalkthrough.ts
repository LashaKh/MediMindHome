export type CaseRole = keyof typeof CASE_ROLES;
type Roster = {
  departments: { slug: string; seats: string[] }[];
  seats: { email: string; role: string | null }[];
  users: { id: number; name: string; dept_slug: string; roles: string; seat_ok: boolean }[];
};
function roleMatch(role: CaseRole, roles: string | null) {
  return roles?.split(",").some((name) => CASE_ROLES[role].match.includes(name.trim()));
}
export function caseSeatOptions(role: CaseRole, roster: Roster | null) {
  const dept = roster?.departments.find((d) => d.slug === CASE_ROLES[role].dept);
  return roster?.seats.filter((s) =>
    dept?.seats.includes(s.email) && roleMatch(role, s.role) &&
    !s.email.startsWith("mts.clinic.")
  ).map(({ email, role: name }) => ({ email, role: name })) ?? [];
}
export function casePeopleOptions(role: CaseRole, roster: Roster | null) {
  return roster?.users.filter((u) =>
    u.seat_ok && u.dept_slug === CASE_ROLES[role].dept && roleMatch(role, u.roles)
  )
    .map(({ id, name, roles }) => ({ id, name, roles })) ?? [];
}
