-- Sales CRM — one row per buying organization, plus an activity timeline.
--
--   kind = 'target'  researched hospital, not engaged yet (contacts are not pipeline)
--   kind = 'deal'    engaged hospital moving through the 6 sales stages
--   kind = 'anchor'  signed anchor customer (GeoHospitals) — never counted as new pipeline
--
-- Same lock-down as the investor tables: RLS on, anon/authenticated revoked.
-- Only the landing API (track-event?route=crm, service role, admin JWT) reads or writes.

create table if not exists public.crm_accounts (
  id                  uuid primary key default gen_random_uuid(),
  ref                 bigint generated by default as identity unique,
  kind                text not null default 'target'
                        check (kind in ('target', 'deal', 'anchor')),
  name                text not null check (char_length(name) between 1 and 200),
  org_type            text check (org_type in ('group', 'single', 'clinic', 'government')),
  sites               integer check (sites >= 0),
  city                text,
  source              text check (source in ('founder_network', 'warm_intro', 'direct_outreach', 'inbound')),
  stage               text check (stage in ('discovery', 'qualified', 'evaluation_agreed', 'evaluating',
                                            'proposal', 'negotiation', 'won', 'lost')),
  stage_since         date,
  status              text check (status in ('active', 'waiting_on_us', 'waiting_on_it', 'stalled', 'on_hold')),
  owner               text,
  next_step           text,
  next_step_date      date,
  last_touch          date,
  connector           text,
  champion            text,
  buyer               text,
  roles_reached       text,
  pain                text,
  pain_status         text check (pain_status in ('hypothesis', 'confirmed')),
  objections          text,
  last_sent           text,
  current_software    text,
  current_spend_gel   numeric check (current_spend_gel >= 0),   -- per month
  amount_gel          numeric check (amount_gel >= 0),          -- deal value per year
  decision_date       date,
  price_reaction      text,
  concessions         text,
  team_hours          numeric check (team_hours >= 0),
  -- Milestone dates: the first time each happened. Never overwritten by stage moves.
  first_contact_at    date,
  discovery_at        date,
  sql_at              date,
  data_access_at      date,
  eval_agreed_at      date,
  delivered_at        date,
  first_test_at       date,
  results_reviewed_at date,
  signed_at           date,
  lost_reason         text,
  evidence_link       text,
  notes               text,
  researched_on       date,
  excluded            boolean not null default false,
  archived            boolean not null default false,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create table if not exists public.crm_activities (
  id          uuid primary key default gen_random_uuid(),
  account_id  uuid not null references public.crm_accounts(id) on delete cascade,
  type        text not null check (type in ('note', 'call', 'meeting', 'email',
                                             'created', 'stage', 'status', 'owner', 'next_step',
                                             'moved', 'archived', 'restored', 'inbound')),
  body        text check (char_length(body) <= 5000),
  meta        jsonb,
  author      text,
  occurred_at timestamptz not null default now()
);

create index if not exists idx_crm_accounts_live       on public.crm_accounts(kind) where not archived;
create index if not exists idx_crm_activities_account  on public.crm_activities(account_id, occurred_at desc);
create index if not exists idx_crm_activities_occurred on public.crm_activities(occurred_at desc);

alter table public.crm_accounts   enable row level security;
alter table public.crm_activities enable row level security;

revoke all on public.crm_accounts   from anon, authenticated;
revoke all on public.crm_activities from anon, authenticated;
